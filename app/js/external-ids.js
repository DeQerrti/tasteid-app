// ══════════════════════════════════════════════
//  EXTERNAL IDS – номера тайтла в чужих базах
//
//  Зачем. Названия между сервисами не сходятся никогда: перевод,
//  регистр, двоеточие, год в скобках. Единственный надёжный способ
//  понять, что "Тетрадь смерти" из выгрузки и заведённая у нас
//  "Death Note" – один тайтл, это номер в общей базе.
//
//  Хранится всегда парой "чья база + номер":
//    "ids": { "anilist": 145369, "mal": 1535 }
//  Голое число без имени базы через полгода бесполезно – непонятно,
//  чьё оно.
//
//  Общая валюта по аниме и манге – номер MyAnimeList: Шикимори
//  использует его напрямую (запись 38000 там же, что и на MAL),
//  а AniList хранит его рядом со своим, в поле idMal. Через это
//  и цепляется импорт.
//
//  Здесь только разбор уже сохранённых ссылок на обложки – то, что
//  можно достать без обращения к сети. Подключается редактором отзыва
//  (add.html): при сохранении номера вытаскиваются из ссылки на обложку
//  и складываются в ids, а импорт и сравнение паспортов потом сходятся
//  по ним.
// ══════════════════════════════════════════════

// Разбирает ссылку на обложку и возвращает то, что из неё достаётся.
// Возвращает объект вида { anilist: 145369 } или {}, если в ссылке
// номера нет.
//
// Важно: у разных баз в ссылке на картинку лежит РАЗНОЕ.
//   AniList   – в имени файла стоит номер самого тайтла: bx145369-…
//   Hardcover – в пути стоит номер издания: /edition/32349247/…
//   TMDB      – только путь к постеру (1A1Bwg…jpg), номера фильма нет
//   IGDB      – только номер картинки (co8m3r), номера игры нет
// Поэтому для TMDB и IGDB номер придётся спрашивать у их API по
// названию – из ссылки его не выкрутить.
function extractIdsFromCover(cover) {
  const ids = {};
  if (!cover || typeof cover !== "string") return ids;

  // AniList. Две формы за годы: со служебным префиксом (bx145369-hash.png)
  // и старая, без него (41237.jpg).
  const anilist = cover.match(
    /anilistcdn\/media\/(?:anime|manga)\/cover\/[^/]+\/[a-z]*(\d+)[-.]/
  );
  if (anilist) ids.anilist = Number(anilist[1]);

  // Hardcover. Ссылка на картинку – это ссылка-обёртка, внутри которой
  // адрес оригинала лежит закодированным в параметре url.
  if (cover.includes("hardcover.app")) {
    let decoded = cover;
    try {
      decoded = decodeURIComponent(cover);
    } catch {
      // битая последовательность %-кодов – работаем с исходной строкой
    }
    // Годятся только /edition/ и /editions/: это номера изданий.
    // Пути /external_data/ и /book_mappings/ тоже содержат числа, но
    // это номера служебных записей, к книге они не ведут.
    const edition = decoded.match(/assets\.hardcover\.app\/editions?\/(\d+)\//);
    if (edition) ids.hardcover_edition = Number(edition[1]);
  }

  return ids;
}

// Сливает уже сохранённые номера с найденными, не затирая то, что
// проставлено вручную или дозапрошено у API.
function mergeIds(existing, found) {
  const merged = { ...(existing || {}) };
  for (const [key, value] of Object.entries(found || {})) {
    if (merged[key] === undefined || merged[key] === null || merged[key] === "") {
      merged[key] = value;
    }
  }
  return merged;
}

