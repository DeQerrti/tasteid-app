const KNOWN_FILES = new Set([
  "reviews.json",
  "favorites.json",
  "characters-tier.json",
  "site-settings.json",
]);

// Свои коллекции тир-листа: tier-<id>.json, где id приходит из
// slugify() в настройках.
//
// Латиницей id ограничивать нельзя: slugify намеренно сохраняет
// кириллицу, и «Опенинги» превращается в «опенинги-ab12» — для
// русскоязычного приложения это первый же случай, а не край.
//
// Запрещено ровно то, что делает имя опасным или незаписываемым:
// разделители пути, точка (она отделяет расширение), пробелы и знаки,
// которые Windows не пускает в имя файла. Дефис разрешён — slugify
// ставит его и между словами, и перед хвостом-суффиксом.
export const TIER_ID = /^[^\s/\\.:*?"<>|\x00-\x1f]{1,60}$/;

function isTierFile(name) {
  const m = /^tier-(.+)\.json$/i.exec(name);
  return !!m && TIER_ID.test(m[1]);
}

export function isAllowedFile(name) {
  return KNOWN_FILES.has(name) || isTierFile(name);
}
