const KNOWN_FILES = new Set([
  "reviews.json",
  "favorites.json",
  "characters-tier.json",
  "site-settings.json",
]);

// Свои коллекции тир-листа: tier-<id>.json, где id приходит из
// slugify() в настройках.
//
// Латиницей id ограничивать нельзя: slugify намеренно сохраняет
// кириллицу, и «Опенинги» превращается в «опенинги-ab12» – для
// русскоязычного приложения это первый же случай, а не край.
//
// Запрещено ровно то, что делает имя опасным или незаписываемым:
// разделители пути, точка (она отделяет расширение), пробелы и знаки,
// которые Windows не пускает в имя файла. Дефис разрешён – slugify
// ставит его и между словами, и перед хвостом-суффиксом.
export const TIER_ID = /^[^\s/\\.:*?"<>|\x00-\x1f]{1,60}$/;

function isTierFile(name) {
  const m = /^tier-(.+)\.json$/i.exec(name);
  return !!m && TIER_ID.test(m[1]);
}

export function isAllowedFile(name) {
  return KNOWN_FILES.has(name) || isTierFile(name);
}

// Дата версии – из её же имени файла в .history: имя и есть время
// сохранения, отдельного stat() не нужно (и на телефоне он не так
// надёжен). Здесь, а не в одном из двух хранилищ, по той же причине,
// что и правила имён выше: разбор общий, разъезжаться ему нельзя.
//
// Хвост «-1», «-2» появляется у версий, сохранённых в одну и ту же
// миллисекунду (см. #archive), и раньше ломал разбор: регулярка ждала
// Z на конце и до суффикса не доходила. Последствий было два, и оба
// молчаливых – в списке вместо даты стояло «дата неизвестна», а
// возрастная чистка такие версии не трогала совсем: Date.parse давал
// NaN, а NaN там пропускается как «возраст неизвестен».
export function historyDate(fileName) {
  const stamp = fileName.replace(/\.json$/, "").replace(/-\d+$/, "");
  return stamp.replace(/-(\d{2})-(\d{2})-(\d{3})Z$/, ":$1:$2.$3Z");
}

// Имя, которое на самом деле не имя, а шаг вверх по папкам: ".", ".."
// и их варианты с хвостом из точек и пробелов (". .", "..  " – Windows
// молча отбрасывает точки и пробелы в конце имени, и такое имя стало бы
// тем же самым "..").
//
// Раньше вместо этого отвергалось любое имя, где ДВЕ ТОЧКИ ПОДРЯД стоят
// где угодно. Это задевало обычные файлы: «Clive Jr..webp» (сокращение с
// точкой перед расширением) не читался вообще, и после перехода
// синхронизации на чтение картинок по одной (см. readMediaFile в
// core/api.js) одна такая картинка роняла всю синхронизацию с «Картинка
// не читается». Разделителей пути в сегменте и так быть не может (их
// проверяют отдельно), а без них две точки внутри имени никуда не ведут.
export function isDotSegment(name) {
  return String(name).replace(/[. ]+$/, "") === "";
}

// ── Какие версии истории оставить ───────────────
// Порядок версий: по времени из имени, а при совпадении – по номеру
// «-1», «-2». Простая сортировка строк ставила «…Z-1.json» РАНЬШЕ
// «…Z.json» (дефис меньше точки), и при чистке удалялась не та.
function historyKey(fileName) {
  const m = /^(.*?)(?:-(\d+))?\.json$/.exec(fileName);
  const stamp = m ? m[1] : fileName;
  return { time: Date.parse(historyDate(fileName)) || 0, n: m && m[2] ? Number(m[2]) : 0, stamp };
}

export function compareHistoryNames(a, b) {
  const ka = historyKey(a);
  const kb = historyKey(b);
  return ka.time - kb.time || ka.n - kb.n || (a < b ? -1 : a > b ? 1 : 0);
}

// Сколько версий держать и какие. Раньше – просто 50 последних, и любая
// серия быстрых сохранений их вытесняла: импорт с AniList (по записи на
// каждого персонажа и каждое ♥), вечер с «+1» на счётчике серий. Версия
// «до импорта» пропадала, и откатить неудачный импорт было нечем.
//
// Теперь: последние HISTORY_RECENT – всегда; из более старых – только
// «устоявшиеся» состояния, после которых HISTORY_SETTLE_MS ничего не
// менялось (то есть то, что было перед очередной серией правок), пока
// всего не наберётся HISTORY_LIMIT. Места на диске столько же, но в
// истории остаются точки, к которым правда хочется вернуться.
export const HISTORY_LIMIT = 50;
const HISTORY_RECENT = 30;
const HISTORY_SETTLE_MS = 10 * 60 * 1000;

export function historyToRemove(names, limit = HISTORY_LIMIT) {
  const sorted = names.filter((n) => n.endsWith(".json")).sort(compareHistoryNames);
  if (sorted.length <= limit) return [];
  const keep = new Set(sorted.slice(-Math.min(HISTORY_RECENT, limit)));
  for (let i = sorted.length - keep.size - 1; i >= 0 && keep.size < limit; i--) {
    const gap = historyKey(sorted[i + 1]).time - historyKey(sorted[i]).time;
    if (gap >= HISTORY_SETTLE_MS) keep.add(sorted[i]);
  }
  return sorted.filter((n) => !keep.has(n));
}
