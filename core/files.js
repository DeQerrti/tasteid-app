const KNOWN_FILES = new Set([
  "reviews.json",
  "favorites.json",
  "characters-tier.json",
  "site-settings.json",
]);

// Свои коллекции тир-листа: tier-<id>.json, где id приходит из
// slugify() в настройках.
//
// Латиницей id ограничивать нельзя: slugify намеренно сохраняет
// кириллицу, и «Опенинги» превращается в «опенинги-ab12» — для
// русскоязычного приложения это первый же случай, а не край.
//
// Запрещено ровно то, что делает имя опасным или незаписываемым:
// разделители пути, точка (она отделяет расширение), пробелы и знаки,
// которые Windows не пускает в имя файла. Дефис разрешён — slugify
// ставит его и между словами, и перед хвостом-суффиксом.
export const TIER_ID = /^[^\s/\\.:*?"<>|\x00-\x1f]{1,60}$/;

function isTierFile(name) {
  const m = /^tier-(.+)\.json$/i.exec(name);
  return !!m && TIER_ID.test(m[1]);
}

export function isAllowedFile(name) {
  return KNOWN_FILES.has(name) || isTierFile(name);
}

// Дата версии — из её же имени файла в .history: имя и есть время
// сохранения, отдельного stat() не нужно (и на телефоне он не так
// надёжен). Здесь, а не в одном из двух хранилищ, по той же причине,
// что и правила имён выше: разбор общий, разъезжаться ему нельзя.
//
// Хвост «-1», «-2» появляется у версий, сохранённых в одну и ту же
// миллисекунду (см. #archive), и раньше ломал разбор: регулярка ждала
// Z на конце и до суффикса не доходила. Последствий было два, и оба
// молчаливых — в списке вместо даты стояло «дата неизвестна», а
// возрастная чистка такие версии не трогала совсем: Date.parse давал
// NaN, а NaN там пропускается как «возраст неизвестен».
export function historyDate(fileName) {
  const stamp = fileName.replace(/\.json$/, "").replace(/-\d+$/, "");
  return stamp.replace(/-(\d{2})-(\d{2})-(\d{3})Z$/, ":$1:$2.$3Z");
}
